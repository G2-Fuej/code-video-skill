def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", action="store_true", help="720p30 fast preview")
    ap.add_argument("--check-only", action="store_true",
                    help="validate the brief and write spec/prompt without rendering")
    ap.add_argument("--out", default=str(ROOT / "out"))
    args = ap.parse_args()

    # core reads W/H/FPS at import time, so a different frame size needs a fresh
    # interpreter -- re-exec once with the geometry in the environment.
    if args.preview and os.environ.get("CODE_VIDEO_PREVIEW") != "1":
        env = dict(os.environ)
        env.update({"CODE_VIDEO_W": "1280", "CODE_VIDEO_H": "720",
                    "CODE_VIDEO_FPS": "30", "CODE_VIDEO_PREVIEW": "1"})
        cmd = [sys.executable, str(pathlib.Path(__file__).resolve())] + sys.argv[1:]
        raise SystemExit(subprocess.call(cmd, env=env))

    brief = json.loads(json.dumps(BRIEF))  # deep copy
    if args.preview:
        brief["width"], brief["height"], brief["fps"] = 1280, 720, 30
        brief["output"] = "PCL-preview.mp4"

    problems = brief_mod.validate(brief)
    if problems:
        print("[brief] INVALID:")
        for p in problems:
            print(f"  - {p}")
        raise SystemExit(1)
    print("[brief] ok")

    spec = brief_mod.build_spec(brief)

    out_dir = pathlib.Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "brief.json").write_text(json.dumps(brief, ensure_ascii=False, indent=2),
                                        encoding="utf-8")
    (out_dir / "spec.json").write_text(json.dumps(spec, ensure_ascii=False, indent=2),
                                       encoding="utf-8")
    (out_dir / "prompt.md").write_text(brief_mod.render_prompt(brief), encoding="utf-8")

    print(f"[spec] {len(spec['timeline'])} acts -> {out_dir/'spec.json'}")
    for item in spec["timeline"]:
        print(f"  {item['start']:6.2f} - {item['end']:6.2f}  {item['style']}")

    video = out_dir / brief["output"]
    if args.check_only:
        print("[check-only] spec and prompt written, no render")
        return
    director.render(spec, str(video), workdir=str(out_dir / "_work"))
    for k, v in director.probe(video).items():
        print(f"{k}: {v}")
    print(f"size: {video.stat().st_size/1048576:.1f} MB")


if __name__ == "__main__":
    main()